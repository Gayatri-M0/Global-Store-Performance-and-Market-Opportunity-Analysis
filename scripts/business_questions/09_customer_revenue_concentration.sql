-- D) Customer Contribution
/* Q.9) How concentrated is customer revenue, and 
	what proportion of total revenue is generated by the retailer's highest-spending customers? */

WITH CustomerRevenue AS (
	SELECT 
		c.CustomerKey,
		SUM(s.Quantity * s.NetPrice / NULLIF(ExchangeRate, 0)) AS Revenue
	FROM clean_data.sales s
	LEFT JOIN clean_data.customer c
	ON S.CustomerKey = c.CustomerKey
	GROUP BY c.CustomerKey
),

RevenueContribution AS (
	SELECT
		CustomerKey,
		Revenue,
		Revenue * 100.0 / NULLIF(SUM(Revenue) OVER(), 0) AS RevenueContribution
	FROM CustomerRevenue
)

SELECT
	CustomerKey,
	ROUND(Revenue, 2) AS Revenue,
	RANK() OVER(ORDER BY Revenue DESC) AS RevenueRank,
	CONCAT(ROUND(RevenueContribution, 2), '%') AS RevenueContribution,
	CONCAT(ROUND(SUM(RevenueContribution) OVER(ORDER BY Revenue DESC ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW), 2), '%') AS CumulativeRevenueContribution
FROM RevenueContribution
